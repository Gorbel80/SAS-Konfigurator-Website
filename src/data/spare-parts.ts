export function getSparePartById(id: string): SparePart | undefined {
  return spareParts.find((p) => p.id === id);
}

export function getSparePartsForProduct(productId: string): SparePart[] {
  return spareParts.filter((p) => p.compatibleProductIds.includes(productId));
}

export function getSparePartsByCategory(category: SparePart["category"]): SparePart[] {
  return spareParts.filter((p) => p.category === category);
}
